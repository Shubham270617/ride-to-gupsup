// ============================================================================
// Wording of the RTG Lab pages (/lab, /lab/strava, /lab/ridge) and of the
// Membership pages (/membership, /membership/checkout).
//
// Each entry is one editable text of Admin -> Site Content: `field` is its
// name, `label` what the admin sees, `text` the wording shown until an admin
// saves their own. It is stored in site_settings under
// "text.<page>.<field>" (text.lab.*, text.ridge.*, text.membership.*).
//
// The LISTS on those pages are not here — they are tables with their own
// admin screens (Lab — …, Ridge Repeats — …, Membership — …).
//
// Rich text: a field marked `type: "textarea"` may use
//   a blank line  -> a new paragraph
//   ## Heading    -> a small heading
//   **words**     -> bold
// Words in {curly brackets} are filled in by the page (e.g. {count}).
// ============================================================================

const t = (group, field, label, text, type = "text") => ({ group, field, label, type, text });

